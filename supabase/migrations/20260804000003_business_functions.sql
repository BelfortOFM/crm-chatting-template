-- Business calculation functions. Pay periods are computed on the fly here
-- too (never persisted), mirroring lib/period.ts on the client.

create or replace function fn_period_bounds(p_year int, p_month int, p_period_number int)
returns table (period_start date, period_end date)
language sql
immutable
as $$
  select
    case p_period_number
      when 1 then make_date(p_year, p_month, 1)
      when 2 then make_date(p_year, p_month, 8)
      when 3 then make_date(p_year, p_month, 16)
      when 4 then make_date(p_year, p_month, 23)
    end as period_start,
    case p_period_number
      when 1 then make_date(p_year, p_month, 7)
      when 2 then make_date(p_year, p_month, 15)
      when 3 then make_date(p_year, p_month, 22)
      when 4 then (date_trunc('month', make_date(p_year, p_month, 1)) + interval '1 month' - interval '1 day')::date
    end as period_end;
$$;

-- Sum of sale_lines for a shift, in the model's original currency.
create or replace function fn_shift_entry_total(p_shift_entry_id uuid)
returns numeric
language sql
stable
as $$
  select coalesce(sum(amount), 0)
  from sale_lines
  where shift_entry_id = p_shift_entry_id;
$$;

-- Same total converted to EUR, using the model's currency and the rate
-- frozen on the shift entry at declaration time.
create or replace function fn_shift_entry_total_eur(p_shift_entry_id uuid)
returns numeric
language sql
stable
as $$
  select case
    when m.currency = 'EUR' then fn_shift_entry_total(p_shift_entry_id)
    else fn_shift_entry_total(p_shift_entry_id) * se.exchange_rate_used
  end
  from shift_entries se
  join models m on m.id = se.model_id
  where se.id = p_shift_entry_id;
$$;

-- Total EUR revenue generated by a chatter over an arbitrary date range.
create or replace function fn_chatter_period_revenue(p_chatter_id uuid, p_period_start date, p_period_end date)
returns numeric
language sql
stable
as $$
  select coalesce(sum(fn_shift_entry_total_eur(se.id)), 0)
  from shift_entries se
  where se.chatter_id = p_chatter_id
    and se.shift_date between p_period_start and p_period_end;
$$;

-- Full monthly picture for a chatter: total, per-period breakdown,
-- end-of-month forecast (avg declared daily revenue x days in month),
-- and previous month total for comparison.
create or replace function fn_chatter_monthly_summary(p_chatter_id uuid, p_month date)
returns table (
  chatter_id uuid,
  month date,
  total_month_eur numeric,
  period_1_eur numeric,
  period_2_eur numeric,
  period_3_eur numeric,
  period_4_eur numeric,
  forecast_eur numeric,
  previous_month_eur numeric
)
language plpgsql
stable
as $$
declare
  v_year int := extract(year from p_month)::int;
  v_month int := extract(month from p_month)::int;
  v_month_start date := make_date(v_year, v_month, 1);
  v_month_end date := (date_trunc('month', v_month_start) + interval '1 month' - interval '1 day')::date;
  v_days_in_month int := extract(day from v_month_end)::int;
  v_days_elapsed int;
  v_p1 record;
  v_p2 record;
  v_p3 record;
  v_p4 record;
  v_p1_total numeric;
  v_p2_total numeric;
  v_p3_total numeric;
  v_p4_total numeric;
  v_total numeric;
  v_forecast numeric;
  v_prev_month_start date := (v_month_start - interval '1 month')::date;
  v_prev_month_end date := (v_month_start - interval '1 day')::date;
  v_prev_total numeric;
begin
  select * into v_p1 from fn_period_bounds(v_year, v_month, 1);
  select * into v_p2 from fn_period_bounds(v_year, v_month, 2);
  select * into v_p3 from fn_period_bounds(v_year, v_month, 3);
  select * into v_p4 from fn_period_bounds(v_year, v_month, 4);

  v_p1_total := fn_chatter_period_revenue(p_chatter_id, v_p1.period_start, v_p1.period_end);
  v_p2_total := fn_chatter_period_revenue(p_chatter_id, v_p2.period_start, v_p2.period_end);
  v_p3_total := fn_chatter_period_revenue(p_chatter_id, v_p3.period_start, v_p3.period_end);
  v_p4_total := fn_chatter_period_revenue(p_chatter_id, v_p4.period_start, v_p4.period_end);

  v_total := v_p1_total + v_p2_total + v_p3_total + v_p4_total;

  if current_date > v_month_end then
    v_days_elapsed := v_days_in_month; -- past month: no extrapolation needed
  elsif current_date >= v_month_start then
    v_days_elapsed := extract(day from current_date)::int;
  else
    v_days_elapsed := 0; -- future month
  end if;

  if v_days_elapsed > 0 then
    v_forecast := (v_total / v_days_elapsed) * v_days_in_month;
  else
    v_forecast := 0;
  end if;

  v_prev_total := fn_chatter_period_revenue(p_chatter_id, v_prev_month_start, v_prev_month_end);

  return query select
    p_chatter_id,
    v_month_start,
    v_total,
    v_p1_total,
    v_p2_total,
    v_p3_total,
    v_p4_total,
    v_forecast,
    v_prev_total;
end;
$$;

-- Agency leaderboard over an arbitrary period. SECURITY DEFINER so it can
-- read every chatter's revenue regardless of the caller's own row-level
-- visibility, but only for the caller's own agency (or an admin of it) —
-- never an arbitrary agency_id.
create or replace function fn_agency_leaderboard(p_agency_id uuid, p_period_start date, p_period_end date)
returns table (chatter_id uuid, full_name text, total_eur numeric, rank bigint)
language plpgsql
security definer
set search_path = public
stable
as $$
begin
  if not is_agency_member(p_agency_id) then
    raise exception 'not authorized for this agency';
  end if;

  return query
  select
    p.id as chatter_id,
    p.full_name,
    coalesce(fn_chatter_period_revenue(p.id, p_period_start, p_period_end), 0) as total_eur,
    rank() over (
      order by coalesce(fn_chatter_period_revenue(p.id, p_period_start, p_period_end), 0) desc
    ) as rank
  from profiles p
  where p.agency_id = p_agency_id
    and p.role = 'chatter'
  order by total_eur desc;
end;
$$;

-- Same, but for a full month (cumulative), reusing fn_chatter_monthly_summary.
create or replace function fn_agency_leaderboard_month(p_agency_id uuid, p_month date)
returns table (chatter_id uuid, full_name text, total_eur numeric, rank bigint)
language plpgsql
security definer
set search_path = public
stable
as $$
begin
  if not is_agency_member(p_agency_id) then
    raise exception 'not authorized for this agency';
  end if;

  return query
  select
    p.id as chatter_id,
    p.full_name,
    coalesce(s.total_month_eur, 0) as total_eur,
    rank() over (order by coalesce(s.total_month_eur, 0) desc) as rank
  from profiles p
  left join lateral fn_chatter_monthly_summary(p.id, p_month) s on true
  where p.agency_id = p_agency_id
    and p.role = 'chatter'
  order by total_eur desc;
end;
$$;

grant execute on function
  fn_period_bounds(int, int, int),
  fn_shift_entry_total(uuid),
  fn_shift_entry_total_eur(uuid),
  fn_chatter_period_revenue(uuid, date, date),
  fn_chatter_monthly_summary(uuid, date),
  fn_agency_leaderboard(uuid, date, date),
  fn_agency_leaderboard_month(uuid, date)
to authenticated;
